// Generate a PocketBase-compatible copy of the same rules used by the hub UI.
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const files = ['hub-core-v156.js', 'hub-spatial-v157.js', 'hub-free-v178.js'];
const target = path.join(root, 'pocketbase/pb_hooks/hub-rules-v221.js');
const source = '// Generated by tools/build-hub-rules-v221.cjs\n'
  + files.map(file => fs.readFileSync(path.join(root, 'renderer', file), 'utf8')).join('\n')
  + '\nmodule.exports = { core: globalThis.GRPGHubCoreV156, spatial: globalThis.GRPGHubSpatialV157 };\n';
if (process.argv.includes('--check')) {
  if (fs.readFileSync(target, 'utf8') !== source) throw Error('PocketBase hub rules are stale');
} else fs.writeFileSync(target, source);
